import { describe, expect, it } from 'vitest';

import { calldata, chainFaults, joe, mapFaults, metadata, sender } from './erc20TestData';
import { changeMap, createOfficialTokenAppFixture, createTokenAppFixture } from './erc20TestUtils';
import { lock } from './testData';

describe('createAvalancheAppActions ERC20 join', () => {
  /**
   * @target generateTxParameters should consume the generated mainnet overlay member family
   * @dependencies real UI Tokens6.0.2, actual App actions and network; synthetic identity RPC
   * @scenario use native/ERC-20 Avalanche and EIP-004 Ergo definitions with nine significant decimals
   * @expected ten wrapped JOE units transfer ten billion raw units while retaining exact metadata
   */
  it('should consume the generated mainnet overlay member family', async () => {
    const fixture = await createOfficialTokenAppFixture();
    expect(fixture.map.getRawConfig().map((set) => set.ergo.type)).toEqual(['EIP-004', 'EIP-004']);
    expect(await fixture.generate()).toEqual({
      to: joe.tokenId,
      from: sender,
      data: calldata.replace('174876e800', '02540be400'),
      chainId: '0xa86a',
    });
  });
  /**
   * @target generateTxParameters should preserve the frozen JOE example through actual App actions
   * @dependencies real provider/actions/network/TokenMap and generic EVM producer
   * @scenario build the frozen ten-wrapped-unit JOE request on synthetic mainnet identity
   * @expected exact token/custody/amount/metadata bytes and mainnet selection remain unchanged
   */
  it('should preserve the frozen JOE example through actual App actions', async () => {
    const fixture = await createTokenAppFixture();
    expect(await fixture.generate()).toEqual({
      to: joe.tokenId,
      from: sender,
      data: calldata,
      chainId: '0xa86a',
    });
    expect(fixture.rpc.send).toHaveBeenCalledTimes(2);
    expect(fixture.wallet).toHaveBeenCalledTimes(2);
  });

  /**
   * @target generateTxParameters should reject selected asset map defect %s before RPC
   * @dependencies real TokenMap with one-field mutation and actual App producer join
   * @scenario independently alter token/counterpart definition or duplicate an identifier
   * @expected the conversion policy fails before chain observation or transaction generation
   */
  it.each(mapFaults)('should reject selected asset map defect %s before RPC', async (field) => {
    const fixture = await createTokenAppFixture();
    await changeMap(fixture.map, field);
    await expect(fixture.generate()).rejects.toThrow();
    expect(fixture.rpc.send).not.toHaveBeenCalled();
    expect(fixture.wallet).not.toHaveBeenCalled();
  });

  /**
   * @target generateTxParameters should reject selected mainnet identity drift in %s
   * @dependencies actual provider/network/actions; synthetic observer replies
   * @scenario switch only the provider or wallet from mainnet before to Fuji after construction
   * @expected the ERC20 parameters cannot escape the final identity check
   */
  it.each(chainFaults)('should reject selected mainnet identity drift in %s', async (owner) => {
    const fixture = await createTokenAppFixture();
    if (owner === 'provider')
      fixture.rpc.send.mockResolvedValueOnce('0xa86a').mockResolvedValueOnce('0xa869');
    else fixture.wallet.mockResolvedValueOnce(43114n).mockResolvedValueOnce(43113n);
    await expect(fixture.generate()).rejects.toThrow('mismatch');
  });

  /**
   * @target generateTxParameters should capture its caller token before asynchronous map access
   * @dependencies actual server action and TokenMap; synthetic deferred map reader
   * @scenario mutate the caller token decimals inside the map getter after action validation
   * @expected the generated bytes retain the captured18-decimal JOE request
   */
  it('should capture its caller token before asynchronous map access', async () => {
    const fixture = await createTokenAppFixture();
    const token = { ...joe };
    fixture.getTokenMap.mockImplementation(async () => {
      token.decimals = 9;
      return fixture.map;
    });
    expect(
      await fixture.actions.generateTxParameters(
        token.tokenId,
        lock,
        sender,
        10n,
        metadata,
        token,
        'avalanche',
      ),
    ).toEqual({
      to: joe.tokenId,
      from: sender,
      data: calldata,
    });
  });
});
